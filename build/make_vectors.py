"""Write earnumber-v1-vectors.json: test vectors for ports of Ear Number to other languages.
The reference implementation (earnumber.py in the parent directory) defines every expected value.
Deterministic: random.Random(1), sorted keys. Run: PYTHONDONTWRITEBYTECODE=1 python3 build/make_vectors.py"""
import json
import os
import random
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, ROOT)
import earnumber as EN

ABOUT = ("Test vectors for Ear Number version 1, generated by the reference implementation. "
         "decode: for each number 0-999 (as a string key), the thresholds in dB HL at 250, 500, 1000, "
         "2000, 3000, 4000, 6000, 8000 Hz, rounded to 1 decimal; compare within 0.05 dB. "
         "encode: audiograms ({Hz: dB HL}) with the expected number, level (number // 50) and shape "
         "(number % 50); the number must match exactly. pairs: left, right, suffixes, the Damm check "
         "digit and the string format_pair returns with a check digit. parse: strings and the expected "
         "parse_pair result; reject: strings that parse_pair must refuse. Thresholds are given to at "
         "most 3 decimals so that every language reads the same value.")

REQ = (500, 1000, 2000, 4000, 8000)
GRID = (500, 1000, 2000, 3000, 4000, 6000, 8000)


def rec(t, note):
    t = {int(f): v for f, v in t.items()}
    n = EN.encode(t)
    return {"note": note, "thresholds": {str(f): t[f] for f in sorted(t)}, "number": n,
            "level": n // 50, "shape": n % 50}


def grid5(x):
    return round(x / 5) * 5


def random_audiogram(rng, freqs):
    base, slope = rng.uniform(-5, 80), rng.uniform(-5, 45)
    return {f: grid5(min(max(base + slope * max(0.0, (f / 1000) ** 0.5 - 1) * 1.5 + rng.gauss(0, 5), -10), 100))
            for f in freqs}


def encode_vectors(rng):
    v = []
    for x in range(-10, 101, 5):
        v.append(rec({f: x for f in REQ}, f"flat {x}"))
    for k in range(1, 20):
        for d, w in ((-0.01, "below"), (0.01, "above")):
            x = round(5 * k + d, 2)
            v.append(rec({f: x for f in EN.DECODE_FREQS}, f"flat just {w} level boundary {5 * k}"))
    sets = [("five required frequencies", REQ, 40), ("with 3000 and 6000", (500, 1000, 2000, 3000, 4000, 6000, 8000), 30),
            ("with 250", (250, 500, 1000, 2000, 4000, 8000), 20), ("all eight frequencies", EN.DECODE_FREQS, 20)]
    for name, freqs, count in sets:
        for _ in range(count):
            v.append(rec(random_audiogram(rng, freqs), f"sloping, {name}"))
    for _ in range(25):
        t = {f: round(x + rng.uniform(-2.4, 2.4), 1) for f, x in random_audiogram(rng, REQ).items()}
        v.append(rec(t, "off the 5 dB grid"))
    for _ in range(10):
        t = {f: round(rng.uniform(-30, 130), 1) for f in REQ}
        v.append(rec(t, "values outside -10..100, clipped"))
    v.append(rec({f: -40 for f in REQ}, "all far below -10"))
    v.append(rec({f: 150 for f in REQ}, "all far above 100"))
    v.append(rec({f: 100 for f in EN.DECODE_FREQS}, "all 100: no hearing, 000"))
    v.append(rec({f: 100 for f in REQ}, "all 100, required frequencies only: 000"))
    for f in REQ:
        t = {g: 100 for g in REQ}
        t[f] = 95
        v.append(rec(t, f"100 everywhere except {f} Hz at 95"))
    t = {g: 100 for g in REQ}
    t[1000] = 60
    v.append(rec(t, "100 everywhere except 1000 Hz at 60"))
    # near-ties between shapes that are nearest neighbours or adjacent in index
    shapes = EN._table()["shape_residuals_db"]

    def dist(a, b):
        return sum((x - y) ** 2 for x, y in zip(shapes[a], shapes[b]))
    nn = {i: min((j for j in range(1, 50) if j != i), key=lambda j: dist(i, j)) for i in range(1, 50)}
    pairs = []
    for i in rng.sample(range(1, 50), 49):
        p = tuple(sorted((i, nn[i])))
        if p not in pairs:
            pairs.append(p)
        if len(pairs) == 15:
            break
    adj = [(i, i + 1) for i in range(1, 49)]
    for p in rng.sample(adj, len(adj)):
        if p not in pairs:
            pairs.append(p)
        if len(pairs) == 30:
            break
    for a, b in pairs:
        mid = [(x + y) / 2 for x, y in zip(shapes[a], shapes[b])]
        for toward in (a, b):
            t = {f: round(42.5 + m + 0.01 * (c - m), 3) for f, m, c in zip(GRID, mid, shapes[toward])}
            v.append(rec(t, f"near-tie between shapes {a} and {b}, nudged 1% towards {toward}"))
    return v


def pair_vectors(rng):
    out = []
    letters = ["", "", "", "E", "N", "A", "EN", "CE"]
    nums = [0, 1, 49, 50, 999, 7, 705, 688]
    for i in range(40):
        l = nums[i] if i < len(nums) else rng.randrange(1000)
        r = nums[(i + 3) % len(nums)] if i < len(nums) else rng.randrange(1000)
        ls, rs = rng.choice(letters), rng.choice(letters)
        out.append({"left": l, "right": r, "left_suffix": ls, "right_suffix": rs,
                    "check_digit": EN.check_digit(l, r), "formatted": EN.format_pair(l, r, True, ls, rs)})
    return out


def parse_vectors(rng):
    ok = []

    def add(text, l, r, ls="", rs="", c=None):
        ok.append({"text": text, "expect": {"left": l, "right": r, "left_suffix": ls,
                                            "right_suffix": rs, "check": c}})
    c = EN.check_digit(742, 688)
    for text in ("742 688", "742688", "742,688", "742-688", " 742  688 ", "742;688"):
        add(text, 742, 688)
    for text in (f"742 688 {c}", f"742688{c}", f"742,688,{c}", f" 742-688-{c} ", f"742 688{c}"):
        add(text, 742, 688, c=c)
    add("000 000", 0, 0)
    add(f"000 000 {EN.check_digit(0, 0)}", 0, 0, c=EN.check_digit(0, 0))
    add("999 999", 999, 999)
    c2 = EN.check_digit(456, 456)
    add(f"456E 456N {c2}", 456, 456, "E", "N", c2)
    add(f"456e 456n {c2}", 456, 456, "E", "N", c2)
    add(f"456E456N{c2}", 456, 456, "E", "N", c2)
    add("456E 456", 456, 456, "E", "")
    add("456 456N", 456, 456, "", "N")
    add("456EN 456", 456, 456, "EN", "")
    add("456 456 " + str(c2), 456, 456, c=c2)
    add("705,688,%d" % EN.check_digit(705, 688), 705, 688, c=EN.check_digit(705, 688))
    for _ in range(6):
        l, r = rng.randrange(1000), rng.randrange(1000)
        cc = EN.check_digit(l, r)
        add(f"{l:03d} {r:03d} {cc}", l, r, c=cc)
    for e in ok:
        p = EN.parse_pair(e["text"])
        assert p == e["expect"], (e, p)
    bad = [f"742 688 {(c + 1) % 10}", f"742 688 {(c + 5) % 10}", "742 68", "74 688", "742 6881 2",
           "7426881", "742", "", "   ", "abc def", "742O 688", "742I 688", "742S 688", "742 688S",
           "742B 688", "742 688 1 2", "E742 688", "7E42 688", "742 6E88", "742 688 1E", "742 688 X1",
           "742.688", "742 688 12", "4567 688", "742_688"]
    for t in bad:
        try:
            EN.parse_pair(t)
        except ValueError:
            continue
        raise SystemExit(f"expected rejection: {t!r}")
    return ok, bad


def main():
    rng = random.Random(1)
    ok, bad = parse_vectors(rng)
    data = {
        "version": "1",
        "table_sha256": EN.table_sha256(),
        "about": ABOUT,
        "decode": {f"{n:03d}": [round(EN.decode(n)[f], 1) for f in EN.DECODE_FREQS] for n in range(1000)},
        "encode": encode_vectors(rng),
        "pairs": pair_vectors(rng),
        "parse": ok,
        "reject": bad,
    }
    lines = ["{"]
    keys = sorted(data)
    for i, k in enumerate(keys):
        v = data[k]
        end = "," if i < len(keys) - 1 else ""
        if isinstance(v, list):
            lines.append(f' "{k}": [')
            lines.extend("  " + json.dumps(x, sort_keys=True) + ("," if j < len(v) - 1 else "")
                         for j, x in enumerate(v))
            lines.append(" ]" + end)
        elif isinstance(v, dict):
            lines.append(f' "{k}": {{')
            ks = sorted(v)
            lines.extend(f"  {json.dumps(a)}: {json.dumps(v[a])}" + ("," if j < len(ks) - 1 else "")
                         for j, a in enumerate(ks))
            lines.append(" }" + end)
        else:
            lines.append(f" {json.dumps(k)}: {json.dumps(v)}{end}")
    lines.append("}")
    with open(os.path.join(ROOT, "earnumber-v1-vectors.json"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(len(data["encode"]), "encode vectors")


if __name__ == "__main__":
    main()
